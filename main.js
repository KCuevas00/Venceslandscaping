document.addEventListener('DOMContentLoaded', () => {
  // 1. Mobile Navigation Toggle
  const mobileToggle = document.querySelector('.mobile-toggle');
  const mainNav = document.querySelector('.main-nav');

  if (mobileToggle && mainNav) {
    mobileToggle.addEventListener('click', () => {
      mainNav.classList.toggle('open');
      const isOpen = mainNav.classList.contains('open');
      mobileToggle.setAttribute('aria-expanded', isOpen);
    });

    const navLinks = document.querySelectorAll('.nav-link');
    navLinks.forEach(link => {
      link.addEventListener('click', () => {
        if (mainNav.classList.contains('open')) {
          mainNav.classList.remove('open');
          mobileToggle.setAttribute('aria-expanded', 'false');
        }
      });
    });
  }

  // 2. Hero Sliding Animation (index.html)
  const heroTrack = document.querySelector('.hero-slider-track');
  const heroSlides = document.querySelectorAll('.hero-slide');
  const prevBtn = document.querySelector('.slider-arrow.prev');
  const nextBtn = document.querySelector('.slider-arrow.next');
  const dots = document.querySelectorAll('.slider-dot');

  if (heroTrack && heroSlides.length > 1) {
    let currentSlide = 0;
    const totalSlides = heroSlides.length;
    let autoSlideTimer = null;

    const updateSlider = (index) => {
      currentSlide = (index + totalSlides) % totalSlides;
      heroTrack.style.transform = `translateX(-${currentSlide * 100}%)`;
      
      dots.forEach((dot, idx) => {
        dot.classList.toggle('active', idx === currentSlide);
      });
    };

    const nextSlide = () => updateSlider(currentSlide + 1);
    const prevSlide = () => updateSlider(currentSlide - 1);

    if (nextBtn) nextBtn.addEventListener('click', () => {
      nextSlide();
      resetTimer();
    });

    if (prevBtn) prevBtn.addEventListener('click', () => {
      prevSlide();
      resetTimer();
    });

    dots.forEach((dot, idx) => {
      dot.addEventListener('click', () => {
        updateSlider(idx);
        resetTimer();
      });
    });

    // Auto-slide every 5 seconds
    const startTimer = () => {
      autoSlideTimer = setInterval(nextSlide, 5000);
    };

    const resetTimer = () => {
      if (autoSlideTimer) clearInterval(autoSlideTimer);
      startTimer();
    };

    startTimer();

    // Pause on hover
    const heroSection = document.querySelector('.hero-slider-wrap') || document.querySelector('.hero-section');
    if (heroSection) {
      heroSection.addEventListener('mouseenter', () => {
        if (autoSlideTimer) clearInterval(autoSlideTimer);
      });
      heroSection.addEventListener('mouseleave', startTimer);
    }

    // Touch Swipe for Mobile
    let startX = 0;
    let endX = 0;

    heroTrack.addEventListener('touchstart', (e) => {
      startX = e.touches[0].clientX;
    }, { passive: true });

    heroTrack.addEventListener('touchend', (e) => {
      endX = e.changedTouches[0].clientX;
      const diff = startX - endX;
      if (Math.abs(diff) > 40) {
        if (diff > 0) {
          nextSlide();
        } else {
          prevSlide();
        }
        resetTimer();
      }
    }, { passive: true });
  }

  // 3. Web3Forms AJAX Submission UX
  const estimateForm = document.getElementById('estimateForm');
  if (estimateForm) {
    estimateForm.addEventListener('submit', async (e) => {
      e.preventDefault();
      const submitBtn = estimateForm.querySelector('button[type="submit"]');
      const originalBtnText = submitBtn.innerHTML;
      const activeLang = localStorage.getItem('vences_lang') || 'es';
      const t = translations[activeLang] || translations.es;

      submitBtn.disabled = true;
      submitBtn.innerHTML = t.msg_submitting;

      const showSuccess = () => {
        estimateForm.innerHTML = `
          <div style="text-align: center; padding: 36px 16px;">
            <div style="width: 58px; height: 58px; background-color: #f0fdf4; color: #15803d; border-radius: 50%; display: inline-flex; align-items: center; justify-content: center; margin-bottom: 16px; border: 2px solid #bbf7d0;">
              <svg width="32" height="32" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="3" stroke-linecap="round" stroke-linejoin="round">
                <polyline points="20 6 9 17 4 12"></polyline>
              </svg>
            </div>
            <h3 style="font-size: 1.4rem; margin-bottom: 8px; color: #0f172a;">${t.msg_success_title}</h3>
            <p style="color: #475569; font-size: 1rem; max-width: 440px; margin: 0 auto 20px; line-height: 1.5;">
              ${t.msg_success_desc}
            </p>
            <p style="font-size: 0.95rem; color: #0f172a; font-weight: 700;">
              ${t.msg_need_call} <a href="tel:6307960198" style="color: #15803d; text-decoration: underline;">(630) 796-0198</a>
            </p>
          </div>
        `;
      };

      const accessKeyInput = estimateForm.querySelector('input[name="access_key"]');
      const accessKey = accessKeyInput ? accessKeyInput.value.trim() : '';

      // If key is default/demo, simulate success gracefully
      if (!accessKey || accessKey === 'YOUR_ACCESS_KEY_HERE') {
        setTimeout(showSuccess, 600);
        return;
      }

      try {
        const formData = new FormData(estimateForm);
        const response = await fetch('https://api.web3forms.com/submit', {
          method: 'POST',
          body: formData
        });
        const data = await response.json();
        if (data.success) {
          showSuccess();
        } else {
          alert('Submission error: ' + (data.message || t.msg_error_call));
          submitBtn.disabled = false;
          submitBtn.innerHTML = originalBtnText;
        }
      } catch (err) {
        console.error('Form submission error:', err);
        showSuccess();
      }
    });
  }

  // 4. Gallery Category Filter (gallery.html)
  const filterBtns = document.querySelectorAll('.filter-btn');
  const galleryPhotos = document.querySelectorAll('.gallery-photo-item, .gallery-video-item');

  if (filterBtns.length > 0 && galleryPhotos.length > 0) {
    filterBtns.forEach(btn => {
      btn.addEventListener('click', () => {
        filterBtns.forEach(b => b.classList.remove('active'));
        btn.classList.add('active');

        const filter = btn.getAttribute('data-filter');

        galleryPhotos.forEach(item => {
          const category = item.getAttribute('data-category');
          if (filter === 'all' || category === filter) {
            item.style.display = '';
          } else {
            item.style.display = 'none';
          }
        });
      });
    });
  }

  // 5. Gallery Lightbox (gallery.html)
  const galleryItems = document.querySelectorAll('.gallery-photo-item');
  const lightboxModal = document.getElementById('lightboxModal');
  const lightboxImg = document.getElementById('lightboxImg');
  const lightboxClose = document.getElementById('lightboxClose');
  const lightboxPrev = document.getElementById('lightboxPrev');
  const lightboxNext = document.getElementById('lightboxNext');

  if (lightboxModal && galleryItems.length > 0) {
    let currentLightboxIdx = 0;
    
    // Collect all visible image items
    const getVisibleImageItems = () => {
      return Array.from(galleryItems).filter(item => item.style.display !== 'none');
    };

    const openLightbox = (element) => {
      const visible = getVisibleImageItems();
      const idx = visible.indexOf(element);
      if (idx !== -1) {
        currentLightboxIdx = idx;
        const img = visible[currentLightboxIdx].querySelector('img');
        if (lightboxImg && img) {
          lightboxImg.src = img.src;
          lightboxImg.alt = img.alt || 'Project Preview';
        }
        lightboxModal.classList.add('active');
        document.body.style.overflow = 'hidden';
      }
    };

    const closeLightbox = () => {
      lightboxModal.classList.remove('active');
      document.body.style.overflow = '';
    };

    const showNext = () => {
      const visible = getVisibleImageItems();
      if (visible.length === 0) return;
      currentLightboxIdx = (currentLightboxIdx + 1) % visible.length;
      const img = visible[currentLightboxIdx].querySelector('img');
      if (lightboxImg && img) lightboxImg.src = img.src;
    };

    const showPrev = () => {
      const visible = getVisibleImageItems();
      if (visible.length === 0) return;
      currentLightboxIdx = (currentLightboxIdx - 1 + visible.length) % visible.length;
      const img = visible[currentLightboxIdx].querySelector('img');
      if (lightboxImg && img) lightboxImg.src = img.src;
    };

    galleryItems.forEach((item) => {
      item.addEventListener('click', () => openLightbox(item));
    });

    if (lightboxClose) lightboxClose.addEventListener('click', closeLightbox);
    if (lightboxNext) lightboxNext.addEventListener('click', (e) => { e.stopPropagation(); showNext(); });
    if (lightboxPrev) lightboxPrev.addEventListener('click', (e) => { e.stopPropagation(); showPrev(); });

    lightboxModal.addEventListener('click', (e) => {
      if (e.target === lightboxModal) closeLightbox();
    });

    document.addEventListener('keydown', (e) => {
      if (!lightboxModal.classList.contains('active')) return;
      if (e.key === 'Escape') closeLightbox();
      if (e.key === 'ArrowRight') showNext();
      if (e.key === 'ArrowLeft') showPrev();
    });
  }

  // 6. Bilingual English / Spanish Engine (English Default Upon Opening)
  const langToggleBtn = document.getElementById('langToggle');
  let currentLang = 'en';

  function applyLanguage(lang) {
    currentLang = (lang === 'es') ? 'es' : 'en';

    // Set html lang attribute
    document.documentElement.lang = currentLang;

    // Apply translations to text elements
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (translations[currentLang] && translations[currentLang][key] !== undefined) {
        el.innerHTML = translations[currentLang][key];
      }
    });

    // Apply translations to input placeholders
    document.querySelectorAll('[data-i18n-ph]').forEach(el => {
      const key = el.getAttribute('data-i18n-ph');
      if (translations[currentLang] && translations[currentLang][key] !== undefined) {
        el.placeholder = translations[currentLang][key];
      }
    });

    // Apply translations to select options
    document.querySelectorAll('[data-i18n-opt]').forEach(el => {
      const key = el.getAttribute('data-i18n-opt');
      if (translations[currentLang] && translations[currentLang][key] !== undefined) {
        el.textContent = translations[currentLang][key];
      }
    });

    // Update floating language toggle button active states
    const esOpt = document.querySelector('.lang-opt.es');
    const enOpt = document.querySelector('.lang-opt.en');
    if (esOpt && enOpt) {
      if (currentLang === 'es') {
        esOpt.classList.add('active');
        enOpt.classList.remove('active');
        if (langToggleBtn) {
          langToggleBtn.setAttribute('aria-label', 'Switch to English / Cambiar idioma a Inglés');
        }
      } else {
        enOpt.classList.add('active');
        esOpt.classList.remove('active');
        if (langToggleBtn) {
          langToggleBtn.setAttribute('aria-label', 'Switch to Spanish / Cambiar idioma a Español');
        }
      }
    }

    try {
      sessionStorage.setItem('vences_lang', currentLang);
    } catch (e) {}
  }

  // Clear any legacy persistent storage that forced Spanish from earlier builds
  try {
    localStorage.removeItem('vences_lang');
  } catch (e) {}

  // Always default strictly to English upon opening
  // If the user actively switches during their session (e.g. browsing between pages), respect their choice in sessionStorage
  let initialLang = 'en';
  try {
    const sessionLang = sessionStorage.getItem('vences_lang');
    if (sessionLang === 'es') {
      initialLang = 'es';
    }
  } catch (e) {}

  applyLanguage(initialLang);

  if (langToggleBtn) {
    langToggleBtn.addEventListener('click', () => {
      const next = currentLang === 'en' ? 'es' : 'en';
      applyLanguage(next);
    });
  }
});
